def normalize_lang(lang: str | None) -> str:
    if not lang:
        return DEFAULT_LANG
    low = (lang or "").lower()[:2]
    return low if low in LANGS else DEFAULT_LANG


def t(lang: str | None, key: str, **kwargs) -> str:
    entry = T.get(key)
    if entry is None:
        return key
    text = entry.get(normalize_lang(lang)) or entry[DEFAULT_LANG]
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def lang_pack(lang: str) -> dict[str, str]:
    norm = normalize_lang(lang)
    return {key: values.get(norm) or values[DEFAULT_LANG] for key, values in T.items()}


def all_keys() -> set[str]:
    return set(T.keys())
